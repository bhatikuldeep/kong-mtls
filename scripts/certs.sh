#!/usr/bin/env bash
# Creates every certificate the demo needs, in certs/ (git-ignored). Safe to run again: it keeps what exists.
#   client-ca           the CA that issues client certificates (Kong trusts it)
#   client-a, -b, -c    client certificates issued by client-ca, mapped to the gold, silver and bronze consumers
#   client-d            issued by client-ca too, but mapped to no consumer
#   partner             bonus: issued by client-ca, sent to Kong in a header by the edge
#   rogue               a self-signed certificate that claims to be client-a
#   gateway-ca, gateway the certificate Kong serves for api.example.test, and the CA clients use to check it
#   edge                bonus: the certificate the edge serves for edge.example.test, from gateway-ca
#   dp                  the data plane's certificate for its connection to Konnect
#   backend-ca          Part 2: the backend's CA; it signs the two certificates below
#   inventory           Part 2: the certificate the backend serves (Kong checks it against backend-ca)
#   kong-upstream       Part 2: the client certificate Kong presents to the backend
# Then writes kong/certs.yaml: the decK file with the CA certificates (no keys), the gateway's server certificate
# and the client certificate Kong presents to the backend.
set -euo pipefail
cd "$(dirname "$0")/.."
mkdir -p certs
cd certs
DAYS=30


# A CA: Kong only accepts a CA certificate with basicConstraints CA:TRUE
ca() { # name, subject
  [ -f "$1.crt" ] && return
  openssl req -x509 -new -nodes -newkey rsa:2048 -days "$DAYS" -subj "/CN=$2" \
    -keyout "$1.key" -out "$1.crt" -config <(printf '%s\n' \
      '[req]' 'distinguished_name=dn' 'x509_extensions=v3' '[dn]' \
      '[v3]' 'basicConstraints=critical,CA:TRUE' 'keyUsage=critical,keyCertSign,cRLSign' \
      'subjectKeyIdentifier=hash') 2>/dev/null
}

# A leaf certificate signed by a CA: name, CA name, DNS name, extended key usage
leaf() {
  [ -f "$1.crt" ] && return
  openssl req -new -nodes -newkey rsa:2048 -subj "/CN=$3" -keyout "$1.key" -out "$1.csr" 2>/dev/null
  openssl x509 -req -in "$1.csr" -CA "$2.crt" -CAkey "$2.key" -CAcreateserial -days "$DAYS" -out "$1.crt" \
    -extfile <(printf '%s\n' 'basicConstraints=CA:FALSE' 'keyUsage=critical,digitalSignature,keyEncipherment' \
      "extendedKeyUsage=$4" "subjectAltName=DNS:$3") 2>/dev/null
  rm -f "$1.csr"
}

ca client-ca "Example Client CA"
leaf client-a client-ca client-a.example.test clientAuth
leaf client-b client-ca client-b.example.test clientAuth
leaf client-c client-ca client-c.example.test clientAuth
leaf client-d client-ca client-d.example.test clientAuth
leaf partner client-ca partner.example.test clientAuth   # bonus: the edge

# Same name as client-a, but self-signed: it must be rejected
[ -f rogue.crt ] || openssl req -x509 -new -nodes -newkey rsa:2048 -days "$DAYS" \
  -subj "/CN=client-a.example.test" -keyout rogue.key -out rogue.crt \
  -config <(printf '%s\n' '[req]' 'distinguished_name=dn' 'x509_extensions=v3' '[dn]' \
    '[v3]' 'basicConstraints=CA:FALSE' 'extendedKeyUsage=clientAuth' 'subjectAltName=DNS:client-a.example.test') 2>/dev/null

ca gateway-ca "Example Gateway CA"
leaf gateway gateway-ca api.example.test serverAuth
leaf edge gateway-ca edge.example.test serverAuth         # bonus: the edge

# Part 2: the backend's CA, the backend's server certificate and Kong's client certificate for the backend
ca backend-ca "Example Backend CA"
leaf inventory backend-ca inventory serverAuth
leaf kong-upstream backend-ca kong-gateway clientAuth

[ -f dp.crt ] || openssl req -x509 -new -nodes -newkey rsa:2048 -days 365 -subj "/CN=mtls-identity-dp" \
  -keyout dp.key -out dp.crt 2>/dev/null

rm -f ./*.srl
chmod 600 ./*.key

# decK file with the certificates. The IDs are fixed so kong/kong.yaml can reference them.
indent() { sed 's/^/      /' "$1"; }
cat > ../kong/certs.yaml <<EOF
# Generated by scripts/certs.sh from certs/. Do not edit, do not commit.
_format_version: "3.0"
_info:
  select_tags: [mtls-identity]
ca_certificates:
  - id: 5b1e0c62-6f0a-4c39-9a11-000000000001   # Example Client CA: public certificate only, no key
    cert: |
$(indent client-ca.crt)
  - id: 5b1e0c62-6f0a-4c39-9a11-000000000003   # Part 2: Example Backend CA, to check the backend's certificate
    cert: |
$(indent backend-ca.crt)
certificates:
  - id: 5b1e0c62-6f0a-4c39-9a11-000000000002   # what Kong serves for api.example.test
    cert: |
$(indent gateway.crt)
    key: |
$(indent gateway.key)
    snis:
      - name: api.example.test
  - id: 5b1e0c62-6f0a-4c39-9a11-000000000004   # Part 2: the client certificate Kong presents to the backend
    cert: |
$(indent kong-upstream.crt)
    key: |
$(indent kong-upstream.key)
EOF
echo "Certificates in certs/, valid for ${DAYS} days (the data plane's for 365)"
